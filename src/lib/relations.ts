import { type SocioType, type QuadraId } from './socionics-data'

// ---------- 14 интертипных отношений ----------

export type RelationKind =
  | 'тождество' | 'дуальность' | 'активация' | 'зеркальность' | 'родственные'
  | 'полудуальность' | 'деловые' | 'мираж' | 'суперэго' | 'квазитождество'
  | 'погашение' | 'конфликт' | 'ревизия' | 'заказ'

export type DirectedRole = 'ревизор' | 'подревизный' | 'заказчик' | 'подзаказный'

export interface RelationResult {
  kind: RelationKind
  /** Роль первого аргумента (только для ревизии и заказа) */
  roleA?: DirectedRole
  /** Роль второго аргумента (только для ревизии и заказа) */
  roleB?: DirectedRole
}

// Коды ячеек таблицы:
//   T тождество, D дуальность, A активация, Z зеркальность,
//   RO родственные, PD полудуальность, DE деловые, MI мираж,
//   SE суперэго, KV квазитождество, PP погашение («полная
//   противоположность» у Аушры), K конфликт,
//   P+ заказ (в строке — заказчик), P- заказ (в строке — подзаказный),
//   R+ ревизия (в строке — ревизор), R- ревизия (в строке — подревизный)

const KIND_OF: Record<string, RelationKind> = {
  T: 'тождество', D: 'дуальность', A: 'активация', Z: 'зеркальность',
  RO: 'родственные', PD: 'полудуальность', DE: 'деловые', MI: 'мираж',
  SE: 'суперэго', KV: 'квазитождество', PP: 'погашение', K: 'конфликт',
  'P+': 'заказ', 'P-': 'заказ', 'R+': 'ревизия', 'R-': 'ревизия',
}

