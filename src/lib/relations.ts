const ROW_INDEX: Record<string, number> = {}
WIKI_ORDER.forEach((ru, i) => { ROW_INDEX[ru] = i })

/** Отношение между двумя типами (для ревизии и заказа — с ролями) */
export function relationBetween(a: SocioType, b: SocioType): RelationResult {
  const code = TABLE[ROW_INDEX[a.ru]][ROW_INDEX[b.ru]]
  const kind = KIND_OF[code]
  if (!kind) throw new Error(`Неизвестный код отношения: ${code}`)
  if (code === 'P+') return { kind, roleA: 'заказчик', roleB: 'подзаказный' }
  if (code === 'P-') return { kind, roleA: 'подзаказный', roleB: 'заказчик' }
  if (code === 'R+') return { kind, roleA: 'ревизор', roleB: 'подревизный' }
  if (code === 'R-') return { kind, roleA: 'подревизный', roleB: 'ревизор' }
  return { kind }
}

